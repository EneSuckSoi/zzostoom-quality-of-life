"""Builds src/generated/buff_text.cpp: buff names in every menu language.

    py -X utf8 tools/gen_buff_text.py [--cheat-sheet DIR]

The names come from the game's own item / spell text, which zzostoom cheat sheet already
extracted for its item list (src/generated/item_db.cpp = English names in order,
src/generated/game_text.cpp = the same list in each game language). A buff whose English name
is not an item there keeps its English name. Turkish has no game text: English names are used.
Run after tools/extract_buffs.py.
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Order of i18n::Lang; None = no game text for that language.
LANGS = ["en", "deude", "frafr", "spaes", "porbr", "rusru", "jpnjp", "korkr", "zhocn", None]
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"|nullptr')


def c_strings(text):
    """C string literals (or None for nullptr) in order, escapes kept as written."""
    return [m.group(1) if m.group(0) != "nullptr" else None for m in STRING.finditer(text)]


def unescape(s):
    return s.replace('\\"', '"').replace("\\\\", "\\")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cheat-sheet", default=os.path.join(ROOT, "..", "zzostoom-cheat-sheet"))
    a = ap.parse_args()
    gen = os.path.join(a.cheat_sheet, "src", "generated")

    # English item names: 7th field of each kItems row.
    items_src = open(os.path.join(gen, "item_db.cpp"), encoding="utf-8").read()
    items_src = items_src[items_src.index("const ItemDef kItems[]"):]
    english = []
    for line in items_src.splitlines():
        if line.lstrip().startswith("{0x"):
            english.append(unescape(c_strings(line)[0]))
    index_of = {}
    for i, name in enumerate(english):
        index_of.setdefault(name, i)

    text_src = open(os.path.join(gen, "game_text.cpp"), encoding="utf-8").read()
    per_lang = {}
    for code in filter(None, LANGS[1:]):
        start = text_src.index(f"const char* const kItems_{code}[] = {{")
        body = text_src[start:text_src.index("};", start)]
        body = body[body.index("{") + 1:]
        per_lang[code] = c_strings(body)
        assert len(per_lang[code]) == len(english), (code, len(per_lang[code]), len(english))

    buffs_src = open(os.path.join(ROOT, "src", "generated", "buff_db.cpp"), encoding="utf-8").read()
    buffs = [unescape(m.group(1)) for m in re.finditer(r'\{\d+, "((?:[^"\\]|\\.)*)"\}', buffs_src)]

    def cell(s):
        return "nullptr" if s is None else '"' + s + '"'

    out = ["// AUTO-GENERATED by tools/gen_buff_text.py from zzostoom cheat sheet's game text.",
           '#include "i18n.h"', "", "namespace zz::i18n {", "",
           "const char* const kBuffText[][kLangCount] = {"]
    found = 0
    for name in buffs:
        i = index_of.get(name)
        cells = ["nullptr"]  # English: kBuffNames
        for code in LANGS[1:]:
            cells.append(cell(per_lang[code][i]) if code and i is not None else "nullptr")
        found += i is not None
        out.append("    {" + ", ".join(cells) + "},  // " + name)
    out += ["};", f"const int kBuffTextCount = {len(buffs)};", "", "}  // namespace zz::i18n", ""]
    dst = os.path.join(ROOT, "src", "generated", "buff_text.cpp")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{found} of {len(buffs)} buff names translated -> {dst}")
    for name in buffs:
        if name not in index_of:
            print("  English only:", name)


if __name__ == "__main__":
    main()
