"""Generates src/generated/buff_db.cpp: names for timed buffs (SpEffectParam rows the game shows
with an icon), taken from the items and spells that apply them.

    py -X utf8 tools/extract_buffs.py [--regulation PATH] [--msg PATH]

Links followed (offsets verified against the game data, e.g. Exalted Flesh -> 3950 (30 s),
Boiled Crab -> 500820 (60 s), Flame, Grant Me Strength -> 1605000):
  EquipParamGoods +0x04 (refId_default)       -> SpEffectParam
  Magic +0x68..+0x80 (refIds)                  -> SpEffectParam or Bullet
  Bullet (any field)                           -> SpEffectParam or child Bullet (2 levels)
  SpEffectParam without icon (any field)       -> SpEffectParam with icon (1 level)
Only effects with an icon and a duration are kept.
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import souls_formats as sf  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODS = os.path.expandvars(r"%LOCALAPPDATA%\garyttierney\me3\config\profiles\eldenring-mods")
GAME = r"E:\SteamLibrary\steamapps\common\ELDEN RING\Game"


def ints(param, data, rid):
    return struct.unpack_from("<%di" % (param.row_size // 4), data, param.rows[rid])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--regulation", default=os.path.join(MODS, "regulation.bin"))
    ap.add_argument("--msg", default=os.path.join(MODS, "msg", "engus", "item_dlc02.msgbnd.dcx"))
    ap.add_argument("--oodle", default=os.path.join(GAME, "oo2core_6_win64.dll"))
    a = ap.parse_args()

    reg = sf.read_bnd4(sf.dcx_decompress(sf.decrypt_regulation(open(a.regulation, "rb").read()),
                                         a.oodle), a.oodle)
    msg = sf.read_bnd4(sf.dcx_decompress(open(a.msg, "rb").read(), a.oodle), a.oodle)

    def names(base):
        out = {}
        for suffix in ("", "_dlc01", "_dlc02"):
            key = f"{base}{suffix}.fmg"
            if key in msg:
                out.update({k: v.strip() for k, v in sf.read_fmg(msg[key]).items()
                            if v and v.strip() and not v.startswith("[ERROR]")})
        return out

    goods_names = names("GoodsName")
    magic_names = names("GoodsName")  # spells are inventory goods with the same ids
    magic_names.update(names("MagicName"))

    def load(name):
        d = reg[name + ".param"]
        return sf.Param(d), d

    sp, spd = load("SpEffectParam")
    goods, gd = load("EquipParamGoods")
    magic, md = load("Magic")
    bullet, bd = load("Bullet")

    def is_buff(i):
        if i <= 0 or i not in sp.rows:
            return False
        icon, _, endurance = struct.unpack_from("<iff", spd, sp.rows[i])
        return icon > 0 and endurance > 0

    def effects_from_spe(i, depth=1):
        if is_buff(i):
            return [i]
        if depth <= 0 or i not in sp.rows:
            return []
        out = []
        for v in ints(sp, spd, i):
            if v > 0 and v != i and is_buff(v):
                out.append(v)
        return out

    def effects_from_bullet(b, depth=2):
        out = []
        if b not in bullet.rows:
            return out
        for v in ints(bullet, bd, b):
            if v <= 0:
                continue
            if v in sp.rows:
                out += effects_from_spe(v)
            elif depth > 0 and v in bullet.rows and v != b:
                out += effects_from_bullet(v, depth - 1)
        return out

    found = {}  # spEffect id -> name

    def add(effects, name):
        for e in effects:
            found.setdefault(e, name)

    for gid, name in sorted(goods_names.items()):
        if gid not in goods.rows:
            continue
        ref = struct.unpack_from("<i", gd, goods.rows[gid] + 0x04)[0]
        if ref > 0:
            add(effects_from_spe(ref), name)

    for mid, name in sorted(magic_names.items()):
        if mid not in magic.rows:
            continue
        for off in range(0x68, 0x80, 4):
            ref = struct.unpack_from("<i", md, magic.rows[mid] + off)[0]
            if ref <= 0:
                continue
            if ref in bullet.rows:
                add(effects_from_bullet(ref), name)
            elif ref in sp.rows:
                add(effects_from_spe(ref), name)

    rows = sorted(found.items())
    out_path = os.path.join(ROOT, "src", "generated", "buff_db.cpp")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/extract_buffs.py from regulation.bin and item_dlc02.msgbnd.dcx.\n")
        f.write("#include \"buff_db.h\"\n\nnamespace zz::buffs {\n\n")
        f.write(f"const int kBuffNameCount = {len(rows)};\n")
        f.write("const BuffName kBuffNames[] = {\n")
        for i, name in rows:
            esc = name.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f"    {{{i}, \"{esc}\"}},\n")
        f.write("};\n\n}  // namespace zz::buffs\n")
    total = sum(1 for i in sp.rows if is_buff(i))
    print(f"{len(rows)} named buffs (of {total} timed effects with an icon) -> {out_path}")
    for i, name in rows[:12]:
        icon, _, endurance = struct.unpack_from("<iff", spd, sp.rows[i])
        print(f"  {i}: {name} ({endurance:g} s, icon {icon})")


if __name__ == "__main__":
    main()
