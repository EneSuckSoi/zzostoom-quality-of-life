"""Builds src/generated/ui_text.cpp from the translations in lang/<code>.tsv.

    py -X utf8 tools/gen_lang.py

Each .tsv line is "English<TAB>translation". The order of LANGS must match i18n::Lang. A line
whose %d / %s / %u / %.1f don't match the English text is rejected (it would crash printf).
To add a language: add it to LANGS here and to Lang / kLanguages in src/i18n.*, then write
lang/<code>.tsv.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ["en", "de", "fr", "es", "pt", "ru", "ja", "ko", "zh", "tr"]
SPEC = re.compile(r"%[-+ #0]*\d*(?:\.\d+)?[a-zA-Z]")


def cstr(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{s}"'


def main():
    rows = {}  # english -> {lang: text}
    errors = 0
    for i, code in enumerate(LANGS[1:], 1):
        path = os.path.join(ROOT, "lang", code + ".tsv")
        if not os.path.exists(path):
            print(f"warning: {path} missing")
            continue
        for n, line in enumerate(open(path, encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            if "\t" not in line:
                print(f"{code}.tsv:{n}: no tab")
                errors += 1
                continue
            en, text = line.split("\t", 1)
            en, text = en.replace("\\n", "\n"), text.replace("\\n", "\n")  # "\n" = line break
            if SPEC.findall(en.replace("%%", "")) != SPEC.findall(text.replace("%%", "")):
                print(f"{code}.tsv:{n}: format specifiers differ: {en!r} -> {text!r}")
                errors += 1
                continue
            rows.setdefault(en, {})[code] = text
    if errors:
        sys.exit(1)
    out = ["// AUTO-GENERATED by tools/gen_lang.py from lang/*.tsv - edit those instead.",
           '#include "i18n.h"', "", "namespace zz::i18n {", "",
           "const char* const kUiText[][kLangCount] = {"]
    for en, tr in rows.items():
        cells = [cstr(en)] + [cstr(tr[c]) if c in tr else "nullptr" for c in LANGS[1:]]
        out.append("    {" + ", ".join(cells) + "},")
    out += ["};", f"const int kUiTextCount = {len(rows)};", "", "}  // namespace zz::i18n", ""]
    dst = os.path.join(ROOT, "src", "generated", "ui_text.cpp")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{len(rows)} strings -> {dst}")
    for code in LANGS[1:]:
        print(f"  {code}: {sum(1 for t in rows.values() if code in t)}")


if __name__ == "__main__":
    main()
